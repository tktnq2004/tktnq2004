// Builds the GitHub profile README: a browser window whose tabs and menu really
// work, plus three buttons under it.
//
// GitHub strips scripts from READMEs, so the clicks go to a small server (the
// Cloudflare Worker in profile/worker). It remembers which tabs are open and
// sends the visitor back to the profile, and it draws the browser pieces for
// whatever is open right now.
//
// Run from the repo root:  node profile/build.mjs https://<worker>.workers.dev
// The address is saved in profile/worker-url.txt, so later runs need no argument.
// Writes README.md and profile/assets/*.svg. Do not edit those by hand.

import { mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EMAIL, CV, LIVE, svgDoc, text, tw, esc, browserMarkup } from './worker/src/render.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const ASSETS = join(HERE, 'assets');
const URL_FILE = join(HERE, 'worker-url.txt');

const arg = process.argv[2];
const worker = (arg || (existsSync(URL_FILE) ? readFileSync(URL_FILE, 'utf8') : '')).trim().replace(/\/+$/, '');
if (!/^https:\/\/[\w.-]+$/.test(worker)) {
  console.error('Give the Worker address, e.g.  node profile/build.mjs https://tktnq2004-profile.<you>.workers.dev');
  process.exit(1);
}
writeFileSync(URL_FILE, `${worker}\n`);

// ---------------------------------------------------------------- buttons (real links)

const BUTTONS = [
  { id: 'email', label: 'Email me', icon: 'mail', href: `mailto:${EMAIL}` },
  { id: 'cv', label: 'Download CV', icon: 'file', href: CV },
  { id: 'portfolio', label: 'Portfolio', icon: 'globe', href: LIVE },
];

const ICONS = {
  mail: '<rect x="1" y="3" width="16" height="12" rx="2.5" fill="none"/><path d="M2 5l7 5 7-5" fill="none"/>',
  file: '<path d="M4 1.5h6.5L14.5 5.5V16a.5.5 0 0 1-.5.5H4a.5.5 0 0 1-.5-.5V2a.5.5 0 0 1 .5-.5Z" fill="none"/><path d="M10 1.5V6h4.5M6.5 10h5M6.5 13h5" fill="none"/>',
  globe: '<circle cx="9" cy="9" r="7.5" fill="none"/><path d="M1.5 9h15M9 1.5c2.2 2.1 3.3 4.6 3.3 7.5S11.2 14.4 9 16.5M9 1.5C6.8 3.6 5.7 6.1 5.7 9s1.1 5.4 3.3 7.5" fill="none"/>',
};

function button(b) {
  const h = 44;
  const w = Math.round(tw(b.label, 14.5, { bold: true }) + 70);
  const body =
    `<rect x=".75" y=".75" width="${w - 1.5}" height="${h - 1.5}" rx="${h / 2}" class="f-chip s-line" stroke-width="1.5"/>` +
    `<g transform="translate(20 13)" class="s-acc" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">${ICONS[b.icon]}</g>` +
    text(48, 27.5, b.label, { size: 14.5, bold: true });
  return svgDoc(w, h, body);
}

// ---------------------------------------------------------------- write

rmSync(ASSETS, { recursive: true, force: true });
mkdirSync(ASSETS, { recursive: true });
for (const b of BUTTONS) writeFileSync(join(ASSETS, `button-${b.id}.svg`), button(b));

// Plain spaces between the buttons so they can wrap on a phone.
const buttons = BUTTONS.map((b) => `<a href="${esc(b.href)}"><img height="44" src="profile/assets/button-${b.id}.svg" alt="${esc(b.label)}"></a>`).join(' ');

writeFileSync(
  join(ROOT, 'README.md'),
  `<!-- Generated by profile/build.mjs. Edit the script, then run: node profile/build.mjs -->
<p>
${browserMarkup(worker)}
</p>

<p align="center">${buttons}</p>
`,
);

console.log(`wrote README.md and ${BUTTONS.length} buttons for ${worker}`);
